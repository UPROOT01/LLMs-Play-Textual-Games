"""Parallel version of play() from self_evaluation.py: several games are played at the same time, and their answers
are generated by vLLM, which keeps adding the new requests to the batch being generated (continuous batching):
a game does not wait for the self-evaluation of another game to end. vLLM also keeps the context already read
in the previous turns (prefix caching), so it does not read the whole game again at every turn.

Each game runs in its own thread with an unchanged agent (e.g. LLMAgentSelfEvaluate): the agent's model is
replaced by a proxy whose generate() hands the request to vLLM and waits for the answer. So the prompts, the parsing
of the answers and the logs are exactly the same as with play().

Differences with play():
- the answers are generated by vLLM instead of transformers, with the same model and sampling parameters: they are
  sampled from the same distribution, but they are not reproducible (play() calls torch.manual_seed(46) before each game).
- times are wall-clock times (time.perf_counter()) and not CPU times, because the CPU time is shared by all
  the games. They are not comparable with the times measured by play().
- the transformers model loaded by self_evaluation.py is moved to the CPU to leave the GPU memory to vLLM:
  after play_parallel(), restart the kernel before using play().
"""
import itertools
import os
import re
import threading
import time

import torch
import textworld
import textworld.gym

import self_evaluation
from self_evaluation import tokenizer, model_name

_env_lock = threading.Lock() # TextWorld is not thread-safe (global game registry and game parser): one game action at a time
_engine = None
_request_ids = itertools.count() # unique across the calls, since the engine is kept


def _get_engine(gpu_memory_utilization):
    global _engine
    if _engine is None:
        self_evaluation.model.to("cpu")
        torch.cuda.empty_cache()
        os.environ.setdefault("VLLM_ENABLE_V1_MULTIPROCESSING", "0") # engine in this process: no subprocess to spawn from the notebook
        os.environ.setdefault("VLLM_LOGGING_LEVEL", "WARNING")
        from vllm import LLM
        _engine = LLM(model=model_name, gpu_memory_utilization=gpu_memory_utilization,
                      max_model_len=32768, enable_prefix_caching=True, seed=46).llm_engine
    return _engine


def _sampling_params(kwargs):
    """The vLLM equivalent of the arguments the agent passes to model.generate()."""
    from vllm import SamplingParams
    generation_config = self_evaluation.model.generation_config # the defaults of model.generate()
    params = {name: getattr(generation_config, name, None) for name in ("temperature", "top_p", "top_k", "min_p")}
    params.update({name: kwargs[name] for name in params if name in kwargs})
    params = {name: value for name, value in params.items() if value is not None}
    return SamplingParams(max_tokens=kwargs["max_new_tokens"],
                          stop_token_ids=[kwargs.get("eos_token_id", tokenizer.eos_token_id)],
                          **params)


class _VLLMModel:
    """Stands in for the model inside an agent: generate() hands the request to the main thread and waits for the answer."""
    def __init__(self, queue):
        self.queue = queue

    def generate(self, input_ids, **kwargs):
        request = {"ids": input_ids[0].tolist(), "kwargs": kwargs, "output": None}
        with self.queue.condition:
            self.queue.pending.append(request)
            self.queue.condition.notify_all()
            self.queue.condition.wait_for(lambda: request["output"] is not None or self.queue.error is not None)
            if self.queue.error is not None:
                raise RuntimeError("parallel play stopped") from self.queue.error
        return torch.tensor([request["ids"] + request["output"]], device="cpu")


class _Queue:
    def __init__(self):
        self.condition = threading.Condition()
        self.pending = [] # requests not yet handed to vLLM
        self.finished = [] # (key, path, result or exception) of the games that ended
        self.running = 0 # games that have not ended yet
        self.error = None # set when the main thread stops, to wake up and stop the games


def _play_game(agent, path, max_steps, loop_window, loop_max_distinct):
    """One episode of play(), with wall-clock times. Returns the list of (moves, score, time) of the episode."""
    infos_to_request = agent.infos_to_request
    infos_to_request.max_score = True
    with _env_lock:
        env_id = textworld.gym.register_games([path], request_infos=infos_to_request, max_episode_steps=max_steps)
        env = textworld.gym.make(env_id)
    try:
        episode_start = time.perf_counter()
        with _env_lock:
            obs, infos = env.reset()
        score = 0
        done = False
        nb_moves = 0
        moves_scores_times = [(0, 0, 0)]
        turns = []
        loop = False
        while not done:
            command = agent.act(obs, score, done, infos)
            turns.append((re.sub(r">\s+-=.*", "", obs).strip(), command))
            timestamp = time.perf_counter()
            with _env_lock:
                obs, score, done, infos = env.step(command)
            nb_moves += 1
            moves_scores_times.append((nb_moves, score, timestamp - episode_start))
            if not done and loop_window and len(turns) >= loop_window \
                    and len(set(turns[-loop_window:])) <= loop_max_distinct:
                if hasattr(agent, "write_on_log"):
                    agent.write_on_log(f"LOOP DETECTED: episode stopped at step {nb_moves}")
                loop = True
                break
        agent.act(obs, score, True, infos)
        return moves_scores_times, infos["max_score"], loop, time.perf_counter() - episode_start
    finally:
        with _env_lock:
            env.close()


def play_parallel(jobs, n_parallel=4, max_steps=100, loop_window=None, loop_max_distinct=2, on_result=None,
                  verbose=True, gpu_memory_utilization=0.85):
    """Plays one episode of every job, n_parallel games at a time.
    jobs: list of (key, make_agent, path): make_agent() returns a new agent (e.g. LLMAgentSelfEvaluate), path is the game.
    on_result(key, moves_scores_times): called in the main thread as soon as a game ends, in the order the games end.
    Returns {key: moves_scores_times}, where moves_scores_times is the same list play() returns for one episode.
    """
    engine = _get_engine(gpu_memory_utilization)
    queue = _Queue()
    jobs = list(jobs)
    results = {}
    in_vllm = {} # request id -> request being generated
    start = time.perf_counter()
    generated_tokens = 0
    display_handle = None
    last_display = 0

    def run(key, agent, path):
        try:
            outcome = _play_game(agent, path, max_steps, loop_window, loop_max_distinct)
        except BaseException as e:
            outcome = e
        with queue.condition:
            queue.finished.append((key, path, outcome))
            queue.running -= 1
            queue.condition.notify_all()

    try:
        while jobs or queue.running > 0:
            while jobs and queue.running < n_parallel:
                key, make_agent, path = jobs.pop(0)
                agent = make_agent()
                agent.model = _VLLMModel(queue)
                with queue.condition:
                    queue.running += 1
                threading.Thread(target=run, args=(key, agent, path), daemon=True).start()

            with queue.condition:
                if not in_vllm: # nothing to generate: wait until a game asks for a generation or ends
                    queue.condition.wait_for(lambda: queue.pending or queue.finished, timeout=1)
                new_requests, queue.pending = queue.pending, []
                done_now, queue.finished = queue.finished, []

            for request in new_requests:
                request_id = str(next(_request_ids))
                in_vllm[request_id] = request
                engine.add_request(request_id, {"prompt_token_ids": request["ids"]}, _sampling_params(request["kwargs"]))

            for key, path, outcome in done_now:
                if isinstance(outcome, BaseException):
                    raise outcome
                moves_scores_times, max_score, loop, seconds = outcome
                results[key] = moves_scores_times
                if verbose:
                    print(f"{path} {'loop detected, ' if loop else ''}steps: {moves_scores_times[-1][0]}; "
                          f"score: {moves_scores_times[-1][1]} / {max_score}; time: {seconds:.0f} s")
                if on_result is not None:
                    on_result(key, moves_scores_times)

            if in_vllm:
                for output in engine.step(): # one generation step of all the requests in the batch
                    if output.finished:
                        request = in_vllm.pop(output.request_id)
                        generated_tokens += len(output.outputs[0].token_ids)
                        with queue.condition:
                            request["output"] = list(output.outputs[0].token_ids)
                            queue.condition.notify_all()

            if verbose and time.perf_counter() - last_display > 2: # the loop runs at every generated token
                last_display = time.perf_counter()
                elapsed = last_display - start
                text = f"{queue.running} games running, {len(jobs)} waiting; {len(results)} ended " \
                     + f"({len(results) / elapsed * 3600:.1f} games/hour); {generated_tokens / elapsed * 60:.0f} tokens/min overall"
                try:
                    from IPython.display import display
                    if display_handle is None:
                        display_handle = display({"text/plain": text}, raw=True, display_id=True)
                    else:
                        display_handle.update({"text/plain": text}, raw=True)
                except ImportError:
                    pass
    finally:
        if in_vllm:
            engine.abort_request(list(in_vllm))
        with queue.condition:
            if queue.running > 0 and queue.error is None:
                queue.error = RuntimeError("stopped") # wakes up the game threads, which then stop
            queue.condition.notify_all()
    return results
